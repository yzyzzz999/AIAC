def apply_colormap(temp_celsius: np.ndarray) -> np.ndarray:
    """Map temperature matrix (H,W) to Ironbow RGB image (H,W,3) uint8.

    Uses per-frame auto-ranging: min->index 0, max->index 255.
    """
    t_min = temp_celsius.min()
    t_max = temp_celsius.max()
    t_range = t_max - t_min

    if t_range < 0.01:
        return np.full((*temp_celsius.shape, 3), 128, dtype=np.uint8)

    scaled = (temp_celsius - t_min) * (255.0 / t_range)
    indices = scaled.astype(np.uint8)

    rgb = IRONBOW_LUT[indices]
    return rgb[::-1, ::-1]  # rotate 180°
